#!/usr/bin/env python3
"""Reference library manager (stdlib only). Layout and rubric: references/inspiration/library-update.md

  library.py add --title "Linear changelog" --url https://linear.app/changelog --kind website \
      --found-via "Awwwards SOTD 2026-10-20" --tags saas,dark,typography --steal "..." \
      --score craft=5,clarity=4,originality=4,transferability=4,evidence=3 --ethics pass
  library.py reject --url https://... --reason "scroll-jacking, fails contrast"
  library.py search <term> [<term> ...]     # all terms must match title/tags/body
  library.py index                          # rebuild library/index.yaml from entries/
  library.py check                          # validate entries (fields, rubric, duplicates)
"""
import argparse, datetime, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
LIB = ROOT / "library"
ENTRIES = LIB / "entries"
KINDS = {"app", "website", "flow", "component", "brand", "type", "motion", "data-viz", "design-system"}
CRITERIA = ["craft", "clarity", "originality", "transferability", "evidence"]


def slugify(s):
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")[:60]


def norm_url(u):
    u = re.sub(r"[?#].*$", "", u.strip())
    return re.sub(r"^https?://(www\.)?", "", u).rstrip("/").lower()


def parse(path):
    text = path.read_text(encoding="utf-8")
    meta, body = {}, text
    if text.startswith("---"):
        _, fm, body = text.split("---", 2)
        for line in fm.splitlines():
            m = re.match(r"^([a-z_]+):\s*(.*?)\s*(#.*)?$", line)
            if m:
                meta[m.group(1)] = m.group(2).strip('"')
    meta["_body"], meta["_path"] = body.strip(), path
    return meta


def entries():
    return [parse(p) for p in sorted(ENTRIES.rglob("*.md"))]


def known_urls():
    urls = {norm_url(e.get("url", "")): e["_path"].name for e in entries()}
    rej = LIB / "rejected.yaml"
    if rej.exists():
        for m in re.finditer(r"url:\s*(\S+)", rej.read_text()):
            urls.setdefault(norm_url(m.group(1)), "rejected.yaml")
    return urls


def add(a):
    if a.kind not in KINDS:
        sys.exit(f"--kind must be one of {sorted(KINDS)}")
    dup = known_urls().get(norm_url(a.url))
    if dup:
        sys.exit(f"duplicate of {dup}")
    score = dict(kv.split("=") for kv in a.score.split(",")) if a.score else {}
    total = sum(int(score.get(c, 0)) for c in CRITERIA)
    if a.ethics == "fail" and a.role != "anti-example":
        sys.exit("ethics=fail entries can only be added with --role anti-example")
    if a.role == "exemplar" and score and (total < 17 or min(int(score.get(c, 0)) for c in CRITERIA) < 2):
        sys.exit(f"below curation bar (total {total}/25, need >=17 with no criterion <2); use --role technique or reject")
    date = a.date or datetime.date.today().isoformat()
    eid = f"{date}-{slugify(a.title)}"
    path = ENTRIES / date[:4] / f"{eid}.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    sc = ", ".join(f"{c}: {score.get(c, '?')}" for c in CRITERIA)
    path.write_text(f"""---
id: {eid}
title: "{a.title}"
url: {a.url}
found_via: "{a.found_via or 'manual'}"
kind: {a.kind}
tags: [{a.tags}]
role: {a.role}
shipped: true
added: {date}
seen_on: {date}
status: active
score: {{ {sc}, ethics: {a.ethics} }}
total: {total}
---

## What to steal (principle, 1–3 bullets)
- {a.steal or 'TODO'}

## Why it works

## Where it applies / where it doesn't

## Style DNA (optional, compact)

## Notes / open questions
""", encoding="utf-8")
    print(path.relative_to(ROOT))


def reject(a):
    dup = known_urls().get(norm_url(a.url))
    if dup:
        sys.exit(f"already known: {dup}")
    with open(LIB / "rejected.yaml", "a", encoding="utf-8") as f:
        f.write(f"- url: {a.url}\n  reason: \"{a.reason}\"\n  date: {a.date or datetime.date.today().isoformat()}\n")
    print("rejected")


def search(terms):
    terms = [t.lower() for t in terms]
    for e in entries():
        hay = " ".join(str(v) for k, v in e.items() if k != "_path").lower()
        if all(t in hay for t in terms):
            steal = re.search(r"## What to steal.*?\n- (.+)", e["_body"])
            print(f"{e.get('title')} [{e.get('kind')}, {e.get('role')}, {e.get('total')}/25] {e.get('url')}\n   steal: {steal.group(1) if steal else '-'}\n   file: {e['_path'].relative_to(ROOT)}")


def index():
    rows = entries()
    out = ["# Generated by scripts/library.py index. Do not edit by hand.", f"count: {len(rows)}", "entries:"]
    for e in rows:
        out.append(f"  - {{id: {e.get('id')}, title: \"{e.get('title')}\", url: {e.get('url')}, kind: {e.get('kind')}, "
                   f"role: {e.get('role')}, tags: {e.get('tags', '[]')}, total: {e.get('total')}, added: {e.get('added')}, status: {e.get('status')}}}")
    (LIB / "index.yaml").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"indexed {len(rows)} entries")


def check():
    seen, bad = {}, 0
    for e in entries():
        p = e["_path"].relative_to(ROOT)
        for field in ("id", "title", "url", "kind", "role", "added", "status"):
            if not e.get(field):
                print(f"{p}: missing {field}"); bad += 1
        if e.get("kind") not in KINDS:
            print(f"{p}: bad kind {e.get('kind')}"); bad += 1
        if "TODO" in e["_body"]:
            print(f"{p}: 'What to steal' still TODO"); bad += 1
        u = norm_url(e.get("url", ""))
        if u in seen:
            print(f"{p}: duplicate url of {seen[u]}"); bad += 1
        seen[u] = p
    print("ok" if not bad else f"{bad} problem(s)")
    sys.exit(1 if bad else 0)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("add")
    p.add_argument("--title", required=True); p.add_argument("--url", required=True)
    p.add_argument("--kind", required=True); p.add_argument("--tags", default="")
    p.add_argument("--found-via"); p.add_argument("--steal"); p.add_argument("--score")
    p.add_argument("--ethics", choices=["pass", "fail"], default="pass")
    p.add_argument("--role", choices=["exemplar", "technique", "anti-example"], default="exemplar")
    p.add_argument("--date")
    r = sub.add_parser("reject"); r.add_argument("--url", required=True); r.add_argument("--reason", required=True); r.add_argument("--date")
    s = sub.add_parser("search"); s.add_argument("terms", nargs="+")
    sub.add_parser("index"); sub.add_parser("check")
    a = ap.parse_args()
    {"add": lambda: add(a), "reject": lambda: reject(a), "search": lambda: search(a.terms),
     "index": index, "check": check}[a.cmd]()


if __name__ == "__main__":
    main()
