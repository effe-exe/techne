#!/usr/bin/env python3
"""Rebuild references/INDEX.md from each reference file's title and its "Use this when" header.

  build_index.py           # write references/INDEX.md
  build_index.py --check   # exit 1 if INDEX.md is stale (no write)
"""
import argparse, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
REF = ROOT / "references"
KEYS = r"(Use this when|Also load when|Also when|Use this for|Covers)"


def summary(path):
    lines = path.read_text(encoding="utf-8").splitlines()
    title = next((l.lstrip("# ").strip() for l in lines if l.startswith("# ")), path.stem)
    uses, current = [], None
    for raw in lines[1:20]:
        l = raw.strip().lstrip(">").strip()
        m = re.match(rf"^\**{KEYS}:?\**:?\s*(.*)", l)
        if m:
            current = m.group(2).strip()
            uses.append(current)
        elif current is not None and l and not l.startswith(("#", "---", "**")):
            uses[-1] += " " + l  # continuation line of a wrapped header
        else:
            current = None
    return title, " / ".join(uses)


def build():
    out = ["# Reference index", "", "Generated by `python3 scripts/build_index.py`. Load only the files the task needs.", ""]
    for folder in sorted(p for p in REF.iterdir() if p.is_dir()):
        files = sorted(f for f in folder.glob("*.md") if f.name != "INDEX.md")
        if not files:
            continue
        out += [f"## {folder.name}/", "", "| File | Use when |", "|---|---|"]
        for f in files:
            title, use = summary(f)
            out.append(f"| [`{f.name}`]({folder.name}/{f.name}) — {title} | {use.replace('|', '/')} |")
        out.append("")
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text, target = build(), REF / "INDEX.md"
    if a.check:
        stale = not target.exists() or target.read_text(encoding="utf-8") != text
        print("stale" if stale else "up to date")
        sys.exit(1 if stale else 0)
    target.write_text(text, encoding="utf-8")
    print("wrote", target)


if __name__ == "__main__":
    main()
